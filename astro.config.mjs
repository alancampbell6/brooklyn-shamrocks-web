import { defineConfig, passthroughImageService } from 'astro/config';
import tailwind from '@astrojs/tailwind';
import sitemap from '@astrojs/sitemap';
import vercel from '@astrojs/vercel/serverless';

export default defineConfig({
  // Static by default; only the pages that opt out with `prerender = false`
  // (/matches and /) are server-rendered on demand to fetch live Foireann data.
  output: 'hybrid',
  // ISR: Vercel caches those renders globally (query strings ignored) and
  // refreshes them in the background every 5 minutes, so visitors get a cached
  // page instead of waiting on a cold function + Foireann round trips.
  adapter: vercel({ isr: { expiration: 300 } }),
  // No page uses astro:assets (responsive images are pre-generated by
  // scripts/responsive-images.mjs), so keep sharp out of the server function.
  image: { service: passthroughImageService() },
  integrations: [tailwind(), sitemap()],
  site: 'https://brooklynshamrocks.com',
});
